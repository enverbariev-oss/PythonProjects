class Category(db.Model):
    __tablename__ = 'categories'
    id = db.Column(db.Integer, primary_key=True)
    name = db.Column(db.String(50), nullable=False)
    image_url = db.Column(db.String(255))
    recipes = db.relationship('Recipe', backref='category', lazy=True)

    def __str__(self):
        return self.name


class Recipe(db.Model):
    __tablename__ = 'recipes'
    id = db.Column(db.Integer, primary_key=True)
    title = db.Column(db.String(100), nullable=False)
    description = db.Column(db.Text)
    ingredients = db.Column(db.Text)
    instructions = db.Column(db.Text)
    image_url = db.Column(db.String(255))
    video_url = db.Column(db.String(255))

    category_id = db.Column(db.Integer, db.ForeignKey('categories.id'), nullable=False)


class RecipeAdminView(ModelView):
    column_list = ('title', 'category', 'description')
    form_columns = ('category', 'title', 'description', 'ingredients', 'instructions', 'image_url', 'video_url')
    column_labels = {
        'category': 'Кухня',
        'title': 'Название блюда',
        'description': 'Краткое описание'
    }

admin.add_view(ModelView(Category, db.session, name="Категории кухонь"))
