@app.context_processor
def inject_categories():
    return dict(all_categories=Category.query.all())

@app.route('/')
def index():
    # Запрашиваем все кухни, а не блюда
    categories = Category.query.all()
    return render_template('index.html', categories=categories)

@app.route('/category/<int:category_id>')
def category_detail(category_id):
    # Находим кухню по ID или выдаем 404
    category = Category.query.get_or_404(category_id)
    # Показываем только те рецепты, у которых category_id совпадает
    recipes = Recipe.query.filter_by(category_id=category_id).all()
    return render_template('category_recipes.html', category=category, recipes=recipes)

# Страница конкретного рецепта
@app.route('/recipe/<int:recipe_id>')
def recipe_detail(recipe_id):
    # Ищем рецепт в базе по ID, если не нашли — выдаем ошибку 404
    recipe = Recipe.query.get_or_404(recipe_id)
    return render_template('recipe_detail.html', recipe=recipe)


@app.route('/api/search', methods=['POST'])
def search_api():
    data = request.get_json()
    query = data.get('query', '').lower()


    recipe = Recipe.query.filter(Recipe.title.ilike(f'%{query}%')).first()

    if recipe:
        return jsonify({
            'success': True,
            'id': recipe.id,
            'name': recipe.title,
            'desc': recipe.description
        })
    return jsonify({'success': False})


